/**
 * behold#1069: writes and checks src/icons.generated.ts, the vendored icon
 * corpus as a module.
 *
 *   tsx src/generate-icons.ts           write src/icons.generated.ts from web/icons (`npm run build` runs this)
 *   tsx src/generate-icons.ts --check   exit 1 when the checked-in module is not what web/icons gives
 *
 * `npm run generate:icons` and `npm run check:icons` are the package scripts.
 * The painter used to read each icon from disk the first time a card asked for
 * it; reading them here, once, at build time is what lets src/render.ts bundle
 * for a browser. web/icons stays the source (scripts/vendor-icons.mjs and
 * scripts/vendor-cloud-icons.mts write it), and the page still loads the cloud
 * boxes' account marks from it.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { splitVendoredSvg } from "./icon-svg.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
export const ICON_ROOT = join(HERE, "..", "web", "icons");
export const GENERATED_ICONS = join(HERE, "icons.generated.ts");

/** Every vendored icon under `root`, as `<dir>/<stem>`, sorted. */
export function vendoredIcons(root: string = ICON_ROOT): string[] {
  const out: string[] = [];
  for (const dir of readdirSync(root, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    for (const f of readdirSync(join(root, dir.name))) {
      if (f.endsWith(".svg")) out.push(`${dir.name}/${f.slice(0, -".svg".length)}`);
    }
  }
  return out.sort();
}

/** The module text for the corpus under `root`. */
export function renderIconModule(root: string = ICON_ROOT): string {
  const rows = vendoredIcons(root).map((rel) => {
    const icon = splitVendoredSvg(readFileSync(join(root, `${rel}.svg`), "utf8"), rel);
    return `  ${JSON.stringify(rel)}: { viewBox: ${JSON.stringify(icon.viewBox)}, body: ${JSON.stringify(icon.body)} },`;
  });
  return [
    "// Generated by src/generate-icons.ts from web/icons. Do not edit:",
    "// run `npm run generate:icons`; `npm run check:icons` fails when this file drifts (behold#1069).",
    'import type { VendoredIcon } from "./icon-svg.ts";',
    "",
    "export const VENDORED_ICONS: Readonly<Record<string, VendoredIcon>> = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}

/** Whether the checked-in module is what the corpus gives. */
export function iconsDrift(root: string = ICON_ROOT, out: string = GENERATED_ICONS): boolean {
  return !existsSync(out) || readFileSync(out, "utf8") !== renderIconModule(root);
}

export function main(argv: readonly string[]): number {
  if (argv.includes("--check")) {
    if (iconsDrift()) {
      console.error("icons: src/icons.generated.ts is not what web/icons gives: run `npm run generate:icons`");
      return 1;
    }
    console.log(`icons: no drift (${vendoredIcons().length} vendored icons)`);
    return 0;
  }
  const text = renderIconModule();
  if (!existsSync(GENERATED_ICONS) || readFileSync(GENERATED_ICONS, "utf8") !== text) writeFileSync(GENERATED_ICONS, text);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (e) {
    console.error(`icons: ${(e as Error).message}`);
    process.exitCode = 1;
  }
}
